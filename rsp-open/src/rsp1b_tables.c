void rsp1b_gain_word(int ifgr, uint16_t *value, uint16_t *index)
{
    uint32_t gain = 0x10001u | ((uint32_t)ifgr << 4);
    uint32_t data = 0x09u | ((gain & 0xffu) << 8) |
                    (((gain >> 8) & 0xffu) << 16) |
                    (((gain >> 16) & 0xffu) << 24);
    *value = (uint16_t)(data & 0xffffu);
    *index = (uint16_t)(data >> 16);
}
